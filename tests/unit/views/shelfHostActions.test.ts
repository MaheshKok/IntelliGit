describe("executeShelfMutationRequest", () => {
    it("copies a selected shelf patch as UTF-8 without opening the export picker", async () => {
        const exportPatch = vi.fn(async () => Buffer.from("diff --git a/a.ts b/a.ts\n"));
        const selectExportDestination = vi.fn(async () => "/host/export.patch");
        const postCompleted = vi.fn();
        writeClipboardText.mockClear();
        writeClipboardText.mockResolvedValueOnce(undefined);

        await executeShelfMutationRequest(
            {
                shelfService: {
                    listShelves: vi.fn(async () => ({
                        shelfIds: ["shelf-1"],
                        corruptShelfIds: [],
                        shelves: [{ id: "shelf-1" }],
                        catalogGeneration: 1,
                    })),
                    getShelfManifest: vi.fn(async () => ({
                        generation: 1,
                        checksum: "a".repeat(64),
                        metadata: {},
                        files: [{ changeId: "change-1" }],
                    })),
                    getShelfFiles: vi.fn(async () => [{ changeId: "change-1" }]),
                    exportPatch,
                },
                refreshData: vi.fn(async () => undefined),
                fireWorkingTreeChanged: vi.fn(),
                selectExportDestination,
            } as never,
            {
                type: "shelfCopyPatchToClipboard",
                requestId: "request-copy",
                shelfId: "shelf-1",
                changeIds: ["change-1"],
                expectedGeneration: 1,
            },
            postCompleted,
        );

        expect(exportPatch).toHaveBeenCalledWith({
            id: "shelf-1",
            changeIds: ["change-1"],
            expectedShelfGeneration: 1,
            expectedShelfChecksum: "a".repeat(64),
        });
        expect(writeClipboardText).toHaveBeenCalledWith("diff --git a/a.ts b/a.ts\n");
        expect(selectExportDestination).not.toHaveBeenCalled();
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ requestId: "request-copy", status: "ok", entries: [] }),
        );
    });

    it("posts an error completion when copying a shelf patch to the clipboard fails", async () => {
        const error = new Error("Clipboard unavailable.");
        const postCompleted = vi.fn();
        writeClipboardText.mockClear();
        writeClipboardText.mockRejectedValueOnce(error);

        await expect(
            executeShelfMutationRequest(
                {
                    shelfService: {
                        listShelves: vi.fn(async () => ({
                            shelfIds: ["shelf-1"],
                            corruptShelfIds: [],
                            shelves: [{ id: "shelf-1" }],
                            catalogGeneration: 1,
                        })),
                        getShelfManifest: vi.fn(async () => ({
                            generation: 1,
                            checksum: "a".repeat(64),
                            metadata: {},
                            files: [{ changeId: "change-1" }],
                        })),
                        getShelfFiles: vi.fn(async () => [{ changeId: "change-1" }]),
                        exportPatch: vi.fn(async () => Buffer.from("patch")),
                    },
                    refreshData: vi.fn(async () => undefined),
                    fireWorkingTreeChanged: vi.fn(),
                } as never,
                {
                    type: "shelfCopyPatchToClipboard",
                    requestId: "request-copy-failure",
                    shelfId: "shelf-1",
                    expectedGeneration: 1,
                },
                postCompleted,
            ),
        ).rejects.toBe(error);

        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({
                requestId: "request-copy-failure",
                status: "error",
                message: "Clipboard unavailable.",
            }),
        );
    });

    it("includes the verbatim mutation failure text in its completion", async () => {
        const postCompleted = vi.fn();
        const error = new Error("Name conflicts with a locked shelf.");
        await expect(
            executeShelfMutationRequest(
                {
                    shelfService: { shelve: vi.fn(async () => Promise.reject(error)) },
                    refreshData: vi.fn(async () => undefined),
                    fireWorkingTreeChanged: vi.fn(),
                } as never,
                shelfSaveMessage,
                postCompleted,
            ),
        ).rejects.toBe(error);
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ message: "Name conflicts with a locked shelf." }),
        );
    });

    it("completes a cancelled host export picker without calling the service", async () => {
        const postCompleted = vi.fn();
        const exportPatch = vi.fn();
        await executeShelfMutationRequest(
            {
                shelfService: { exportPatch },
                refreshData: vi.fn(async () => undefined),
                fireWorkingTreeChanged: vi.fn(),
                selectExportDestination: vi.fn(async () => undefined),
            } as never,
            {
                type: "shelfExportPatch",
                requestId: "request-export",
                shelfId: "shelf-1",
                expectedGeneration: 1,
            },
            postCompleted,
        );
        expect(exportPatch).not.toHaveBeenCalled();
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ requestId: "request-export", status: "ok", entries: [] }),
        );
    });

    it("imports only host-picked patch paths and treats picker cancellation as a successful no-op", async () => {
        const importPatch = vi.fn(async () => ({
            status: "ok" as const,
            entries: [],
            shelfId: "imported",
        }));
        const postCompleted = vi.fn();
        const message = {
            type: "shelfImportPatch",
            requestId: "request-import",
            idempotencyToken: "import-token",
            expectedCatalogGeneration: 4,
        };
        await executeShelfMutationRequest(
            {
                shelfService: {
                    importPatch,
                    listShelves: vi.fn(async () => ({
                        shelfIds: [],
                        corruptShelfIds: [],
                        shelves: [],
                        catalogGeneration: 5,
                    })),
                },
                refreshData: vi.fn(async () => undefined),
                fireWorkingTreeChanged: vi.fn(),
                selectImportSources: vi.fn(async () => ["/host/first.patch", "/host/second.diff"]),
            } as never,
            message,
            postCompleted,
        );
        expect(importPatch).toHaveBeenCalledWith({
            fileUris: ["/host/first.patch", "/host/second.diff"],
            idempotencyToken: "import-token",
            expectedCatalogGeneration: 4,
        });

        await executeShelfMutationRequest(
            {
                shelfService: { importPatch },
                refreshData: vi.fn(async () => undefined),
                fireWorkingTreeChanged: vi.fn(),
                selectImportSources: vi.fn(async () => undefined),
            } as never,
            message,
            postCompleted,
        );
        expect(importPatch).toHaveBeenCalledOnce();
        expect(postCompleted).toHaveBeenLastCalledWith(
            expect.objectContaining({ requestId: "request-import", status: "ok", entries: [] }),
        );
    });

    it("posts typed completion with every per-entry kind after a successful mutation", async () => {
        const shelfService = {
            shelve: vi.fn(async () => ({
                status: "partial" as const,
                shelfId: "shelf-1",
                newGeneration: 3,
                entries: [
                    { kind: "applied" as const, changeId: "change-1" },
                    { kind: "conflicted" as const, changeId: "change-2" },
                    { kind: "retained" as const, changeId: "change-3", reason: "retained" },
                    { kind: "flattenedResidue" as const, changeId: "change-4" },
                    { kind: "refused" as const, changeId: "change-5", reason: "refused" },
                    {
                        kind: "structuralPending" as const,
                        changeId: "change-6",
                        reason: "structural",
                        path: "src/structural.ts",
                        pathFingerprint: "100644:fixture",
                    },
                ],
            })),
            listShelves: vi.fn(async () => ({
                shelfIds: [],
                corruptShelfIds: [],
                shelves: [],
                catalogGeneration: 5,
            })),
        };
        const refreshData = vi.fn(async () => undefined);
        const fireWorkingTreeChanged = vi.fn();
        const postCompleted = vi.fn();

        await executeShelfMutationRequest(
            { shelfService, refreshData, fireWorkingTreeChanged },
            shelfSaveMessage,
            postCompleted,
        );

        expect(shelfService.shelve).toHaveBeenCalledWith({
            name: "before rebase",
            paths: ["src/a.ts"],
            silent: false,
            keepLocal: false,
            idempotencyToken: "save-1",
            expectedCatalogGeneration: 4,
        });
        expect(postCompleted).toHaveBeenCalledWith({
            type: "shelfMutationCompleted",
            requestId: "request-1",
            status: "partial",
            shelfId: "shelf-1",
            newGeneration: 3,
            newCatalogGeneration: 5,
            entries: expect.arrayContaining([
                expect.objectContaining({ kind: "applied", changeId: "change-1" }),
                expect.objectContaining({ kind: "conflicted", changeId: "change-2" }),
                expect.objectContaining({ kind: "retained", changeId: "change-3" }),
                expect.objectContaining({ kind: "flattenedResidue", changeId: "change-4" }),
                expect.objectContaining({ kind: "refused", changeId: "change-5" }),
                expect.objectContaining({ kind: "structuralPending", changeId: "change-6" }),
            ]),
        });
        expect(refreshData).toHaveBeenCalledOnce();
        expect(fireWorkingTreeChanged).toHaveBeenCalledOnce();
    });

    it.each([
        [new RepositoryLockBusyError(), "busy"],
        [new ShelfStaleShelfError(2, 3), "staleShelf"],
        [new ShelfStaleCatalogError(2, 3), "staleCatalog"],
        [new ShelfRecoveryFullError(), "recoveryFull"],
    ] as const)("maps %s to the typed %s completion", async (error, status) => {
        const postCompleted = vi.fn();
        await expect(
            executeShelfMutationRequest(
                {
                    shelfService: { shelve: vi.fn(async () => Promise.reject(error)) },
                    refreshData: vi.fn(async () => undefined),
                    fireWorkingTreeChanged: vi.fn(),
                } as never,
                shelfSaveMessage,
                postCompleted,
            ),
        ).rejects.toBe(error);
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ requestId: "request-1", status, entries: [] }),
        );
    });
});

describe("renderer targeted unshelve", () => {
    const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;
    const unshelveMessage = {
        type: "unshelve",
        requestId: "restore-1",
        shelfId: "shelf-1",
        expectedGeneration: 4,
        changeIds: ["change-1"],
        removeFromShelf: false,
        mode: "flattened",
    } satisfies OutboundMessage;

    const restoreDeps = (status = "applied") => {
        const unshelve = vi.fn(async () => ({
            status,
            entries: [{ kind: "applied" as const, changeId: "change-1" }],
            shelfId: "shelf-1",
            operationId: "00000000-0000-4000-8000-000000000000",
        }));
        const deps = {
            shelfService: {
                repositoryRoot: "/repo",
                unshelve,
                listShelves: vi.fn(async () => ({
                    shelfIds: ["shelf-1"],
                    corruptShelfIds: [],
                    shelves: [{ id: "shelf-1" }, { id: "shelf-2" }],
                    catalogGeneration: 9,
                })),
                getShelfFiles: vi.fn(async () => [{ changeId: "change-1" }]),
                getShelfManifest: vi.fn(async () => ({
                    generation: 4,
                    checksum: "e".repeat(64),
                    metadata: { name: "Shelf", lifecycle: "shelved" },
                    files: [{ changeId: "change-1" }],
                })),
            },
            changelists: {
                get: vi.fn(() => ({
                    revision: 3,
                    activeId: "c",
                    lists: [
                        { id: "c", name: "C", description: "", draft: "" },
                        { id: "d", name: "D", description: "", draft: "" },
                    ],
                    allDraft: "",
                    files: {},
                    changes: {},
                })),
                settled: async () => undefined,
                holdObservers: async () => () => undefined,
            },
            refreshData: vi.fn(async () => undefined),
            fireWorkingTreeChanged: vi.fn(),
        };
        return { deps, unshelve };
    };

    const chooseD = () =>
        showQuickPick.mockImplementation(async (items: { label: string }[]) =>
            items.find((item) => item.label === "D"),
        );

    it("cancel target picker runs zero Git commands", async () => {
        const { deps, unshelve } = restoreDeps();
        showQuickPick.mockReset().mockResolvedValue(undefined);
        const postCompleted = vi.fn();

        await executeShelfMutationRequest(deps as never, unshelveMessage, postCompleted);

        expect(unshelve, "renderer cancellation must not reach the service").not.toHaveBeenCalled();
        expect(deps.fireWorkingTreeChanged).not.toHaveBeenCalled();
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({
                requestId: "restore-1",
                status: "ok",
                entries: [],
                message: "Unshelve cancelled.",
            }),
        );
    });

    it("passes the captured source and target and never accepts a renderer operation", async () => {
        const { deps, unshelve } = restoreDeps();
        showQuickPick.mockReset();
        chooseD();
        const postCompleted = vi.fn();

        await expect(
            executeShelfMutationRequest(
                deps as never,
                {
                    ...unshelveMessage,
                    requestId: "forged",
                    targetOperation: { id: "00000000-0000-4000-8000-000000000001" },
                },
                postCompleted,
            ),
        ).rejects.toThrow("issued by the host");
        expect(unshelve).not.toHaveBeenCalled();

        await executeShelfMutationRequest(
            deps as never,
            { ...unshelveMessage, requestId: "restore-captured" },
            postCompleted,
        );
        expect(unshelve).toHaveBeenCalledWith({
            id: "shelf-1",
            changeIds: ["change-1"],
            removeFromShelf: false,
            mode: "flattened",
            expectedShelfGeneration: 4,
            targetOperation: {
                id: expect.stringMatching(UUID),
                root: "/repo",
                target: { kind: "existing", id: "d", revision: 3 },
                sourceChecksum: "e".repeat(64),
            },
        });
    });

    it.each([
        ["applied", "ok"],
        ["notApplied", "partial"],
        ["conflicted", "conflicts"],
        ["stale", "staleShelf"],
        ["busy", "busy"],
        ["appliedNeedsReview", "needsReview"],
    ] as const)("maps targeted %s to the distinct %s completion", async (result, status) => {
        const { deps } = restoreDeps(result);
        showQuickPick.mockReset();
        chooseD();
        const postCompleted = vi.fn();

        await executeShelfMutationRequest(
            deps as never,
            { ...unshelveMessage, requestId: `restore-${result}` },
            postCompleted,
        );

        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ requestId: `restore-${result}`, status }),
        );
    });

    it("duplicate request returns the known result with no second Git", async () => {
        const { deps, unshelve } = restoreDeps();
        showQuickPick.mockReset();
        chooseD();
        const postCompleted = vi.fn();
        const message = { ...unshelveMessage, requestId: "restore-duplicate" };

        await Promise.all([
            executeShelfMutationRequest(deps as never, message, postCompleted),
            executeShelfMutationRequest(deps as never, message, postCompleted),
        ]);
        await executeShelfMutationRequest(deps as never, message, postCompleted);

        expect(unshelve, "duplicate request must not repeat Git").toHaveBeenCalledOnce();
        expect(postCompleted).toHaveBeenCalledTimes(3);
        const [first, second, third] = postCompleted.mock.calls.map((call) => call[0]);
        expect(second).toEqual(first);
        expect(third).toEqual(first);
    });

    it("reused request ID for a different restore is refused without Git", async () => {
        const { deps, unshelve } = restoreDeps();
        showQuickPick.mockReset();
        chooseD();
        const postCompleted = vi.fn();
        const message = { ...unshelveMessage, requestId: "restore-reused" };

        await executeShelfMutationRequest(deps as never, message, postCompleted);
        await executeShelfMutationRequest(
            deps as never,
            { ...message, shelfId: "shelf-2" },
            postCompleted,
        );

        expect(unshelve).toHaveBeenCalledOnce();
        expect(postCompleted).toHaveBeenLastCalledWith(
            expect.objectContaining({ requestId: "restore-reused", status: "staleShelf" }),
        );
    });

    it("refresh and catalog failures after applied Git keep the applied completion", async () => {
        const { deps } = restoreDeps();
        deps.refreshData.mockRejectedValueOnce(new Error("refresh down"));
        deps.shelfService.listShelves
            .mockResolvedValueOnce({
                shelfIds: ["shelf-1"],
                corruptShelfIds: [],
                shelves: [{ id: "shelf-1" }],
                catalogGeneration: 9,
            })
            .mockRejectedValueOnce(new Error("catalog down"));
        showQuickPick.mockReset();
        chooseD();
        const postCompleted = vi.fn();

        await executeShelfMutationRequest(
            deps as never,
            { ...unshelveMessage, requestId: "restore-refresh" },
            postCompleted,
        );

        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ requestId: "restore-refresh", status: "ok" }),
        );
        expect(deps.fireWorkingTreeChanged).toHaveBeenCalledOnce();
    });
});
