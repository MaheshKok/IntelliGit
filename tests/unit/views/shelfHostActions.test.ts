import { describe, expect, it, vi } from "vitest";

const writeClipboardText = vi.hoisted(() => vi.fn(async () => undefined));
const showQuickPick = vi.hoisted(() => vi.fn());

vi.mock("vscode", () => ({
    env: { clipboard: { writeText: writeClipboardText } },
    l10n: { t: (message: string) => message },
    commands: { executeCommand: vi.fn(async () => undefined) },
    window: {
        showWarningMessage: vi.fn(),
        showInformationMessage: vi.fn(),
        showQuickPick,
        showInputBox: vi.fn(),
    },
}));

import type { OutboundMessage } from "../../../src/webviews/protocol/commitPanelMessages";
import {
    assertShelfChangeId,
    assertShelfGeneration,
    assertShelfId,
    assertShelfName,
    assertShelfToken,
} from "../../../src/views/messageValidation";
import {
    executeShelfMutationRequest,
    openShelfConflictEditorFromMessage,
} from "../../../src/views/commitPanelActions";
import { RepositoryLockBusyError } from "../../../src/git/repositoryLock";
import {
    ShelfRecoveryFullError,
    ShelfStaleCatalogError,
    ShelfStaleShelfError,
} from "../../../src/services/shelfService";

const shelfSaveMessage = {
    type: "shelveSave",
    requestId: "request-1",
    name: "before rebase",
    paths: ["src/a.ts"],
    silent: false,
    keepLocal: false,
    idempotencyToken: "save-1",
    expectedCatalogGeneration: 4,
} satisfies OutboundMessage;

describe("shelf webview validation", () => {
    it.each([undefined, null, 1, true, "", "has space", "x".repeat(129)])(
        "rejects invalid shelf IDs: %j",
        (value) => {
            expect(() => assertShelfId(value, "shelfId")).toThrow();
        },
    );

    it.each([undefined, null, 1, true, "", "bad/id", "x".repeat(129)])(
        "rejects invalid change IDs: %j",
        (value) => {
            expect(() => assertShelfChangeId(value, "changeId")).toThrow();
        },
    );

    it.each([undefined, null, "1", true, -1, 1.2, Number.NaN, Number.POSITIVE_INFINITY])(
        "rejects invalid generations: %j",
        (value) => {
            expect(() => assertShelfGeneration(value, "expectedGeneration")).toThrow();
        },
    );

    it.each([undefined, null, 1, true, "", "x".repeat(257)])(
        "rejects invalid idempotency tokens: %j",
        (value) => {
            expect(() => assertShelfToken(value, "idempotencyToken")).toThrow();
        },
    );

    it.each([undefined, null, 1, true, "", "   ", "bad\0name", "x".repeat(256)])(
        "rejects invalid shelf names without rewriting them: %j",
        (value) => {
            expect(() => assertShelfName(value, "name")).toThrow();
        },
    );

    it("keeps valid shelf names verbatim", () => {
        expect(assertShelfName("  exact shelf name  ", "name")).toBe("  exact shelf name  ");
    });

    it("rejects a client-supplied shelf ID during shelf creation", async () => {
        const postCompleted = vi.fn();
        await expect(
            executeShelfMutationRequest(
                {
                    shelfService: { shelve: vi.fn() },
                    refreshData: vi.fn(async () => undefined),
                    fireWorkingTreeChanged: vi.fn(),
                } as never,
                { ...shelfSaveMessage, shelfId: "client-chosen" },
                postCompleted,
            ),
        ).rejects.toThrow("generated by the host");
        expect(postCompleted).toHaveBeenCalledWith(
            expect.objectContaining({ status: "error", requestId: "request-1" }),
        );
    });
});

